        "        <dir>/<name>/part01.py, part02.py, …",
        "        в исходном файле: from .<name>.part01 import *  (или явные импорты)",
        "    • markdown/текст — режь по смысловым заголовкам:",
        "        docs/<name>/01-<тема>.md, docs/<name>/02-<тема>.md, … + индексный файл",
        "    • json/csv/tsv/xml — партиционируй по записям (например, по 500–1 000 строк):",
        "        data/<name>/part-001.json, part-002.json, …",
        "    • lock/сгенерированное/бинарь — не коммить:",
        "        git rm --cached <файл>  + строка в .gitignore",
        " 2. Собери индекс заново:",
        "      git add <новые части>",
        "      git rm --cached <исходный файл>   # если он заменён частями",
        " 3. Проверь себя до коммита:",
        f"      {hook_cmd} --staged",
        f"      {hook_cmd} --plan <файл>      # готовые команды разреза по строкам",
