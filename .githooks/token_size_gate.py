def build_report(res: Result, cfg: Config, hook_cmd: str) -> str:
    n = len(res.violations)
    rule = "─" * 72
    out = [
        "",
        rule,
        (f"✗ token-size-gate: {n} {plural_ru(n, 'файл', 'файла', 'файлов')} "
         f"в индексе больше лимита {fmt_int(res.limit_tokens)} токенов"),
        (f"  1 токен = {res.bytes_per_token} байта · лимит = {fmt_int(res.max_bytes)} Б "
         f"на файл · проверяются только staged-файлы"),
        rule,
    ]

    for violation in res.violations[:MAX_DETAILED_FILES]:
        ratio = violation.size / res.max_bytes
        out.append(f"  • {violation.path}")
        out.append(
            f"    {fmt_int(violation.size)} Б ≈ {fmt_int(violation.tokens)} токенов · "
            f"превышение ×{ratio:.1f} · нужно ≥ {violation.parts} "
            f"{plural_ru(violation.parts, 'часть', 'части', 'частей')} "
            f"по ≤ {fmt_int(res.max_bytes)} Б")
    if n > MAX_DETAILED_FILES:
        rest = n - MAX_DETAILED_FILES
        out.append(f"  … и ещё {rest} {plural_ru(rest, 'файл', 'файла', 'файлов')}")

    out.append("")
    out.append("ПЛАН РАЗБИЕНИЯ (черновик по границам строк)")
    for violation in res.violations[:MAX_DETAILED_FILES]:
        out.append(f"  {violation.path}:")
        if violation.plan:
            out.extend(split_commands(violation.path, violation.plan))
        else:
            out.append(f"      (файл больше {fmt_int(PLAN_READ_CAP)} Б — "
                       f"режь по смыслу на части ≤ {fmt_int(res.max_bytes)} Б)")
        if violation.plan:
            out.append("      ⚠ для кода разрез по строкам — только черновик: перенеси")
            out.append("        классы/функции в отдельные модули и поправь импорты,")
            out.append("        иначе части не соберутся в рабочий код.")
    out.append("")
    out.extend(build_instructions(cfg, hook_cmd))
    out.append("")
    return "\n".join(out)


