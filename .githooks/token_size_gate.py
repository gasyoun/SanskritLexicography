@dataclass
class Item:
    path: str          # repo-relative, posix
    size: int          # bytes of the staged blob (or worktree file)
    sha: str = ""      # staged blob id, empty for worktree items
    fs: Path | None = None


@dataclass
class Violation:
    path: str
    size: int
    tokens: int
    parts: int
    plan: list = field(default_factory=list)  # [(start, end, bytes, oversized_line)]


@dataclass
class Result:
    source: str
    limit_tokens: int
    max_bytes: int
    bytes_per_token: int
    checked: int
    violations: list
    skipped: list  # [(path, size, reason)]


def blob_sizes(repo: Path, shas: list[str]) -> dict[str, int]:
    if not shas:
        return {}
    payload = ("\n".join(shas) + "\n").encode()
    out = git(repo, "cat-file", "--batch-check=%(objectname) %(objectsize) %(objecttype)",
              input_bytes=payload).stdout
    sizes: dict[str, int] = {}
    for line in out.decode("utf-8", "replace").splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[2] == "blob":
            try:
                sizes[parts[0]] = int(parts[1])
            except ValueError:
                continue
    return sizes


def staged_items(repo: Path) -> list[Item]:
    """Staged added/copied/modified/renamed regular files, from the index."""
    raw = git(repo, "ls-files", "-s", "-z").stdout
    entries: list[tuple[bytes, bytes, int, bytes]] = []
    for record in raw.split(b"\x00"):
        if not record:
            continue
        meta, sep, path = record.partition(b"\t")
        if not sep:
            continue
        fields = meta.split()
        if len(fields) < 3:
            continue
        mode, sha, stage = fields[0], fields[1], fields[2]
        try:
            stage_no = int(stage)
        except ValueError:
            continue
        entries.append((mode, sha, stage_no, path))

    staged_raw = git(repo, "diff", "--cached", "--name-only", "-z",
                     "--diff-filter=ACMR").stdout
    staged = {p for p in staged_raw.split(b"\x00") if p}

    selected = [(sha, path) for mode, sha, stage, path in entries
                if stage == 0 and path in staged and mode.startswith(b"100")]
    sizes = blob_sizes(repo, [sha.decode() for sha, _ in selected])
    items: list[Item] = []
    for sha, path in selected:
        size = sizes.get(sha.decode())
        if size is None:
            continue
        items.append(Item(path=os.fsdecode(path), size=size, sha=sha.decode()))
    return items


def read_blob_head(repo: Path, sha: str, limit: int = MARKER_SCAN_BYTES) -> bytes:
    proc = subprocess.Popen(
        ["git", "-C", str(repo), "cat-file", "blob", sha],
        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    try:
        return proc.stdout.read(limit)
    finally:
        try:
            proc.stdout.close()
        finally:
            proc.kill()
            proc.wait()


def read_blob_all(repo: Path, sha: str) -> bytes | None:
    proc = subprocess.run(["git", "-C", str(repo), "cat-file", "blob", sha],
                          stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                          check=False)
    if proc.returncode != 0:
        return None
    return proc.stdout


def check_attrs(repo: Path, paths: list[str]) -> dict[str, dict[str, str]]:
    """Batch gitattributes lookup for candidate paths (best effort)."""
    if not paths:
        return {}
    payload = b"\x00".join(os.fsencode(p) for p in paths) + b"\x00"
    try:
        out = git(repo, "check-attr", "--stdin", "-z",
                  "linguist-generated", "linguist-vendored", "binary",
                  input_bytes=payload).stdout
    except GateError:
        return {}
    fields = out.split(b"\x00")
    result: dict[str, dict[str, str]] = {}
    for idx in range(0, len(fields) - 2, 3):
        path, attr, value = fields[idx], fields[idx + 1], fields[idx + 2]
        if not path:
            continue
        result.setdefault(os.fsdecode(path), {})[os.fsdecode(attr)] = os.fsdecode(value)
    return result


def read_head(repo: Path, item: Item) -> bytes:
    if item.sha:
        return read_blob_head(repo, item.sha)
    assert item.fs is not None
    with item.fs.open("rb") as fh:
        return fh.read(MARKER_SCAN_BYTES)


def read_all(repo: Path, item: Item) -> bytes | None:
    if item.size > PLAN_READ_CAP:
        return None
    if item.sha:
        return read_blob_all(repo, item.sha)
    assert item.fs is not None
    return item.fs.read_bytes()


# --------------------------------------------------------------------------
# Split plan
# --------------------------------------------------------------------------

def plan_split(data: bytes, max_bytes: int) -> list[tuple[int, int, int, bool]]:
    """Greedy line-boundary split: [(start_line, end_line, size, oversized_line)].

    A line longer than max_bytes cannot be split by lines; it becomes its own
    flagged chunk so the message can tell the user to break it by hand.
    """
    if not data:
        return [(1, 1, 0, False)]
    lines = data.splitlines(keepends=True)
    chunks: list[tuple[int, int, int, bool]] = []
    cur_start = 1
    cur_size = 0
    for idx, line in enumerate(lines, 1):
        if len(line) > max_bytes:
            if cur_size:
                chunks.append((cur_start, idx - 1, cur_size, False))
                cur_size = 0
            chunks.append((idx, idx, len(line), True))
            cur_start = idx + 1
            continue
        if cur_size and cur_size + len(line) > max_bytes:
            chunks.append((cur_start, idx - 1, cur_size, False))
            cur_start = idx
            cur_size = 0
        cur_size += len(line)
    if cur_size:
        chunks.append((cur_start, len(lines), cur_size, False))
    return chunks or [(1, 1, 0, False)]


def split_commands(path: str, chunks: list) -> list[str]:
    stem, ext = os.path.splitext(path)
    width = max(2, len(str(len(chunks))))
    lines = []
    for idx, (start, end, size, oversized) in enumerate(chunks[:MAX_PLAN_LINES], 1):
        out = f"{stem}.part{idx:0{width}d}{ext}"
        note = "  # ⚠ строка длиннее лимита — режь её вручную" if oversized else ""
        lines.append(
            f"      sed -n '{start},{end}p' {shlex.quote(path)} > {shlex.quote(out)}"
            f"   # {fmt_int(size)} Б{note}")
    if len(chunks) > MAX_PLAN_LINES:
        rest = len(chunks) - MAX_PLAN_LINES
        lines.append(f"      … ещё {rest} {plural_ru(rest, 'часть', 'части', 'частей')}: "
                     f"полный план — --plan {shlex.quote(path)}")
    return lines


# --------------------------------------------------------------------------
# Evaluation
# --------------------------------------------------------------------------

def evaluate(repo: Path, cfg: Config, items: list[Item], ignore: list[str],
             source: str, want_plan: bool = True) -> Result:
    skipped: list[tuple[str, int, str]] = []
    oversize: list[Item] = []

    for item in items:
        reason = path_skip_reason(item.path)
        if reason is None:
            pattern = ignore_match(item.path, ignore)
            if pattern:
                reason = f".token-gate-ignore: {pattern}"
        if reason:
            skipped.append((item.path, item.size, reason))
            continue
        if item.size > cfg.max_bytes:
            oversize.append(item)

    attrs = check_attrs(repo, [item.path for item in oversize]) if oversize else {}
    violations: list[Violation] = []

    for item in oversize:
        attr_map = attrs.get(item.path, {})
        attr_reason = None
        for attr, label in (("linguist-generated", "gitattributes: linguist-generated"),
                            ("linguist-vendored", "gitattributes: linguist-vendored"),
                            ("binary", "gitattributes: binary")):
            if attr_is_set(attr_map.get(attr)):
                attr_reason = label
                break
        if attr_reason:
            skipped.append((item.path, item.size, attr_reason))
            continue

        head = read_head(repo, item)
        if looks_binary(head):
            skipped.append((item.path, item.size, "бинарь (NUL-байты в начале файла)"))
            continue
        if is_gate_infrastructure(head):
            skipped.append((item.path, item.size,
                            "патченный хук token-size-gate (инфраструктура)"))
            continue
        marker = looks_generated(head)
        if marker:
            skipped.append((item.path, item.size,
                            f"маркер сгенерированного кода: {marker!r}"))
            continue

        parts = math.ceil(item.size / cfg.max_bytes)
        plan: list = []
        if want_plan:
            data = read_all(repo, item)
            if data is not None:
                plan = plan_split(data, cfg.max_bytes)
        violations.append(Violation(
            path=item.path,
            size=item.size,
            tokens=tokens_of(item.size, cfg.bytes_per_token),
            parts=parts,
            plan=plan,
        ))

    violations.sort(key=lambda v: v.size, reverse=True)
    return Result(source=source, limit_tokens=cfg.limit_tokens,
                  max_bytes=cfg.max_bytes, bytes_per_token=cfg.bytes_per_token,
                  checked=len(items), violations=violations, skipped=skipped)


