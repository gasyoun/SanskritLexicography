def fmt_int(value: int) -> str:
    """1234567 -> '1 234 567' (plain spaces, terminal-safe)."""
    return f"{value:,}".replace(",", " ")


def plural_ru(n: int, one: str, few: str, many: str) -> str:
    n = abs(n) % 100
    if 11 <= n <= 19:
        return many
    n %= 10
    if n == 1:
        return one
    if 2 <= n <= 4:
        return few
    return many


def tokens_of(size: int, bytes_per_token: int) -> int:
    return math.ceil(size / bytes_per_token)


def git(repo: Path, *args: str, input_bytes: bytes | None = None) -> subprocess.CompletedProcess:
    cmd = ["git", "-C", str(repo), *args]
    try:
        proc = subprocess.run(cmd, input=input_bytes,
                              capture_output=True, check=False)
    except FileNotFoundError as exc:
        raise GateError("git не найден в PATH") from exc
    if proc.returncode != 0:
        err = proc.stderr.decode("utf-8", "replace").strip()
        raise GateError(f"git {' '.join(args)}: {err or 'exit ' + str(proc.returncode)}")
    return proc


def resolve_repo() -> Path:
    try:
        proc = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                              capture_output=True, check=False)
    except FileNotFoundError as exc:
        raise GateError("git не найден в PATH") from exc
    if proc.returncode != 0:
        raise GateError("это не git-репозиторий (git rev-parse --show-toplevel)")
    return Path(proc.stdout.decode("utf-8", "surrogateescape").strip())


