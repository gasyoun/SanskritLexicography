        " 4. Повтори git commit.",
        "",
        "ИСКЛЮЧЕНИЯ",
        "  Lock-файлы, сгенерированный код (маркеры @generated / DO NOT EDIT,",
        "  атрибуты linguist-generated / linguist-vendored), вендорные каталоги,",
        "  минифицированные файлы и бинари пропускаются автоматически.",
        "  Свои исключения — в .token-gate-ignore в корне репозитория",
        "  (шаблоны как в .gitignore: docs/generated/**, *.svg):",
        "      echo 'docs/generated/**' >> .token-gate-ignore",
        "  Разовый обход (пишется в .git/token-size-gate.log):",
        "      TOKEN_GATE_ALLOW=1 git commit …",
