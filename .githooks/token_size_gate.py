def path_skip_reason(path: str) -> str | None:
    p = path.replace("\\", "/")
    parts = [seg.lower() for seg in p.split("/") if seg]
    if not parts:
        return None
    base = parts[-1]
    if base in LOG_BASENAMES or base.endswith(LOG_SUFFIXES):
        return "append-only журнал/лог (не делится на части)"
    if base == SELF_BASENAME:
        return "сам гейт (инфраструктура, один файл)"
    if base in LOCK_NAMES or base.endswith((".lock", ".lockb")):
        return "lock-файл"
    for seg in parts[:-1]:
        if seg in GENERATED_DIRS:
            return f"каталог «{seg}/» (сгенерированное/вендорное)"
    if base.endswith(GENERATED_SUFFIXES):
        return "сгенерированный/минифицированный файл"
    if base.endswith(BINARY_SUFFIXES):
        return "бинарь/медиа"
    return None


def looks_binary(head: bytes) -> bool:
    if b"\x00" in head:
        return True
    return head.startswith((b"\xff\xfe", b"\xfe\xff"))


def looks_generated(head: bytes) -> str | None:
    text = head.decode("utf-8", "ignore")
    window = "\n".join(text.splitlines()[:20])
    match = GENERATED_MARKER_RE.search(window)
    return match.group(0) if match else None


def is_gate_infrastructure(head: bytes) -> bool:
    """A patched pre-commit hook carries this marker; it is infrastructure."""
    return GATE_BLOCK_MARKER in head


def load_ignore(repo: Path) -> list[str]:
    ignore_file = repo / ".token-gate-ignore"
    if not ignore_file.is_file():
        return []
    patterns: list[str] = []
    for line in ignore_file.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        patterns.append(line)
    return patterns


def ignore_match(path: str, patterns: list[str]) -> str | None:
    base = path.rsplit("/", 1)[-1]
    for pat in patterns:
        if "/" in pat:
            if fnmatch.fnmatchcase(path, pat):
                return pat
        elif fnmatch.fnmatchcase(base, pat):
            return pat
    return None


def attr_is_set(value: str | None) -> bool:
    return value is not None and value.lower() in {"set", "true", "1", "yes"}


