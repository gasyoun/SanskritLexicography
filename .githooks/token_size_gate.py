#!/usr/bin/env python3
"""token-size-gate — refuse staged files that exceed a token budget.

Formula: 1 token = 4 bytes, so the default 5 000-token budget is 20 000 bytes.

Only the STAGED blob is measured (the index, not the worktree): a file can be
staged large and then shrunk on disk, and it is the staged bytes that would
enter history.

Files that are not written by agents are skipped: lock files, generated code
(content markers, linguist-generated / linguist-vendored attributes), vendored
and generated directories, minified assets, binaries, and anything matched by
.token-gate-ignore in the repository root.

Exit codes: 0 = pass, 1 = budget violation, 2 = gate error (fail-closed).
"""

