def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="token-size-gate",
        description="Pre-commit гейт: запрещает staged-файлы больше лимита "
                    "токенов (1 токен = 4 байта по умолчанию).",
    )
    parser.add_argument("--staged", action="store_true",
                        help="проверить файлы в индексе (режим хука, по умолчанию)")
    parser.add_argument("--check", nargs="+", metavar="PATH",
                        help="проверить файлы рабочей копии (для CI/отладки)")
    parser.add_argument("--explain", metavar="PATH",
                        help="объяснить решение по одному файлу")
    parser.add_argument("--plan", metavar="PATH",
                        help="показать план разреза файла на части")
    parser.add_argument("--limit", type=int, default=None,
                        help=f"лимит в токенах (по умолчанию {DEFAULT_LIMIT_TOKENS})")
    parser.add_argument("--bytes-per-token", type=int, default=None,
                        help=f"байт на токен (по умолчанию {DEFAULT_BYTES_PER_TOKEN})")
    parser.add_argument("--selftest", action="store_true", help="внутренние проверки")
    parser.add_argument("--version", action="version", version=f"%(prog)s {VERSION}")
    return parser


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass

    args = build_parser().parse_args(argv)
    try:
        if args.selftest:
            return selftest()
        cfg = load_config(args)
        repo = resolve_repo()
        if args.plan:
            return cmd_plan(repo, cfg, args.plan)
        if args.explain:
            return cmd_explain(repo, cfg, args.explain)
        if args.check:
            return cmd_check(repo, cfg, args.check)
        return cmd_staged(repo, cfg)
    except GateError as exc:
        print(f"token-size-gate: {exc}", file=sys.stderr)
        print("Коммит заблокирован (fail-closed).", file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        return 2
    except Exception as exc:  # noqa: BLE001 — never fail open
        print(f"token-size-gate: внутренняя ошибка: {exc!r}", file=sys.stderr)
        print("Коммит заблокирован (fail-closed).", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
