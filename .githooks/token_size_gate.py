@dataclass
class Config:
    limit_tokens: int
    bytes_per_token: int

    @property
    def max_bytes(self) -> int:
        return self.limit_tokens * self.bytes_per_token


def load_config(args) -> Config:
    def env_int(name: str, default: int) -> int:
        raw = os.environ.get(name)
        if raw is None or raw == "":
            return default
        try:
            value = int(raw)
        except ValueError as exc:
            raise GateError(f"{name}={raw!r}: нужно целое число") from exc
        if value <= 0:
            raise GateError(f"{name}={value}: нужно положительное число")
        return value

    limit = args.limit if args.limit is not None else env_int(
        "TOKEN_GATE_LIMIT", DEFAULT_LIMIT_TOKENS)
    bpt = args.bytes_per_token if args.bytes_per_token is not None else env_int(
        "TOKEN_GATE_BYTES_PER_TOKEN", DEFAULT_BYTES_PER_TOKEN)
    if limit <= 0:
        raise GateError("--limit должен быть положительным")
    if bpt <= 0:
        raise GateError("--bytes-per-token должен быть положительным")
    return Config(limit_tokens=limit, bytes_per_token=bpt)


def hook_command() -> str:
    argv0 = sys.argv[0] if sys.argv and sys.argv[0] else "pre-commit"
    return f"python3 {shlex.quote(argv0)}"


def log_trip(repo: Path, res: Result, allowed: bool) -> None:
    """Best-effort trip ledger: .git/token-size-gate.log (JSONL)."""
    try:
        out = git(repo, "rev-parse", "--git-path", "token-size-gate.log").stdout
        path = out.decode("utf-8", "replace").strip()
        log_path = Path(path)
        if not log_path.is_absolute():
            log_path = repo / log_path
        log_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "ts": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "source": res.source,
            "limit_tokens": res.limit_tokens,
            "allowed_by_env": allowed,
            "files": [{"path": v.path, "bytes": v.size, "tokens": v.tokens}
                      for v in res.violations],
        }
        with log_path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(payload, ensure_ascii=False) + "\n")
    except Exception:  # noqa: BLE001, S110 — a ledger failure must never pass a block
        pass


def cmd_staged(repo: Path, cfg: Config) -> int:
    items = staged_items(repo)
    res = evaluate(repo, cfg, items, load_ignore(repo), "staged")
    allowed = os.environ.get("TOKEN_GATE_ALLOW") == "1"

    if res.violations:
        log_trip(repo, res, allowed)
        if allowed:
            print("token-size-gate: TOKEN_GATE_ALLOW=1 — блокировка отключена "
                  f"для {len(res.violations)} "
                  f"{plural_ru(len(res.violations), 'файла', 'файлов', 'файлов')}; "
                  "запись в .git/token-size-gate.log", file=sys.stderr)
            return 0
        print(build_report(res, cfg, hook_command()), file=sys.stderr)
        return 1

    if os.environ.get("TOKEN_GATE_VERBOSE") == "1":
        print(f"token-size-gate: проверено {res.checked} staged-файлов, "
              f"превышений нет (лимит {fmt_int(res.limit_tokens)} токенов)", file=sys.stderr)
        for path, size, reason in res.skipped:
            print(f"  skip {path} ({fmt_int(size)} Б): {reason}", file=sys.stderr)
    return 0


def worktree_item(repo: Path, target: str) -> Item:
    path = Path(target)
    if not path.is_absolute():
        path = (Path.cwd() / path).resolve()
    if not path.exists():
        raise GateError(f"файл не найден: {target}")
    try:
        rel = path.relative_to(repo).as_posix()
    except ValueError:
        rel = path.as_posix()
    return Item(path=rel, size=path.stat().st_size, fs=path)


def staged_item_for(repo: Path, target: str) -> Item | None:
    path = Path(target)
    if not path.is_absolute():
        path = (Path.cwd() / path).resolve()
    try:
        rel = path.relative_to(repo).as_posix()
    except ValueError:
        return None
    out = git(repo, "ls-files", "-s", "-z", "--", rel).stdout
    for record in out.split(b"\x00"):
        if not record:
            continue
        meta, sep, p = record.partition(b"\t")
        if not sep:
            continue
        fields = meta.split()
        if len(fields) < 3 or fields[2] != b"0":
            continue
        sha = fields[1].decode()
        size = blob_sizes(repo, [sha]).get(sha)
        if size is None:
            continue
        return Item(path=os.fsdecode(p), size=size, sha=sha)
    return None


def cmd_explain(repo: Path, cfg: Config, target: str) -> int:
    item = staged_item_for(repo, target)
    source = "индекс (staged blob)"
    if item is None:
        item = worktree_item(repo, target)
        source = "рабочая копия"

    reason = path_skip_reason(item.path)
    if reason is None:
        pattern = ignore_match(item.path, load_ignore(repo))
        if pattern:
            reason = f".token-gate-ignore: {pattern}"
    if reason is None and item.size > cfg.max_bytes:
        attrs = check_attrs(repo, [item.path]).get(item.path, {})
        for attr, label in (("linguist-generated", "gitattributes: linguist-generated"),
                            ("linguist-vendored", "gitattributes: linguist-vendored"),
                            ("binary", "gitattributes: binary")):
            if attr_is_set(attrs.get(attr)):
                reason = label
                break
        if reason is None:
            head = read_head(repo, item)
            if looks_binary(head):
                reason = "бинарь (NUL-байты в начале файла)"
            elif is_gate_infrastructure(head):
                reason = "патченный хук token-size-gate (инфраструктура)"
            else:
                marker = looks_generated(head)
                if marker:
                    reason = f"маркер сгенерированного кода: {marker!r}"

    tokens = tokens_of(item.size, cfg.bytes_per_token)
    print(f"Файл: {item.path}")
    print(f"  Источник: {source}")
    print(f"  Размер: {fmt_int(item.size)} Б ≈ {fmt_int(tokens)} токенов")
    print(f"  Лимит: {fmt_int(cfg.max_bytes)} Б = {fmt_int(cfg.limit_tokens)} токенов")
    if item.size > cfg.max_bytes and reason is None:
        parts = math.ceil(item.size / cfg.max_bytes)
        print(f"  Решение: БЛОК — нужно ≥ {parts} "
              f"{plural_ru(parts, 'часть', 'части', 'частей')}")
    elif reason:
        print(f"  Решение: ПРОПУСК — {reason}")
    else:
        print("  Решение: ПРОХОД — в пределах лимита")
    return 0


def cmd_plan(repo: Path, cfg: Config, target: str) -> int:
    item = staged_item_for(repo, target)
    source = "индекс"
    if item is None:
        item = worktree_item(repo, target)
        source = "рабочая копия"

    tokens = tokens_of(item.size, cfg.bytes_per_token)
    print(f"Файл: {item.path} ({source})")
    print(f"  {fmt_int(item.size)} Б ≈ {fmt_int(tokens)} токенов; "
          f"лимит {fmt_int(cfg.max_bytes)} Б = {fmt_int(cfg.limit_tokens)} токенов")
    if item.size <= cfg.max_bytes:
        print("  Файл в пределах лимита — разбиение не требуется.")
        return 0

    data = read_all(repo, item)
    if data is None:
        print(f"  Файл больше {fmt_int(PLAN_READ_CAP)} Б — автоплан недоступен, "
              f"режь по смыслу на части ≤ {fmt_int(cfg.max_bytes)} Б.")
        return 0

    chunks = plan_split(data, cfg.max_bytes)
    print(f"  Нужно частей: ≥ {len(chunks)} "
          f"({plural_ru(len(chunks), 'часть', 'части', 'частей')})")
    print()
    print("  Черновой разрез по границам строк:")
    for line in split_commands(item.path, chunks):
        print(line)
    print()
    print("  ⚠ Для кода это только черновик: перенеси классы/функции в отдельные")
    print("    модули и поправь импорты, иначе части не соберутся в рабочий код.")
    print("  После разреза: git add <новые части> && git rm --cached "
          f"{shlex.quote(item.path)}")
    return 0


def cmd_check(repo: Path, cfg: Config, targets: list[str]) -> int:
    items = [worktree_item(repo, target) for target in targets]
    res = evaluate(repo, cfg, items, load_ignore(repo), "worktree", want_plan=False)
    if res.violations:
        log_trip(repo, res, False)
        print(build_report(res, cfg, hook_command()), file=sys.stderr)
        return 1
    print(f"token-size-gate: проверено {res.checked} файлов, "
          f"превышений нет (лимит {fmt_int(res.limit_tokens)} токенов)")
    return 0


# --------------------------------------------------------------------------
# Internal selftest (unit-level; real git refusal is exercised by tests/)
# --------------------------------------------------------------------------

def selftest() -> int:
    checks = 0

    def check(condition: bool, message: str) -> None:
        nonlocal checks
        checks += 1
        if not condition:
            raise AssertionError(f"selftest failed: {message}")

    check(tokens_of(20_000, 4) == 5_000, "20 000 bytes == 5 000 tokens")
    check(tokens_of(20_001, 4) == 5_001, "20 001 bytes == 5 001 tokens")
    check(tokens_of(1, 4) == 1, "ceil rounding")
    check(plural_ru(1, "файл", "файла", "файлов") == "файл", "plural 1")
    check(plural_ru(3, "файл", "файла", "файлов") == "файла", "plural 3")
    check(plural_ru(11, "файл", "файла", "файлов") == "файлов", "plural 11")
    check(plural_ru(21, "файл", "файла", "файлов") == "файл", "plural 21")

    check(path_skip_reason("package-lock.json") == "lock-файл", "lock file")
    check(path_skip_reason("yarn.lock") == "lock-файл", ".lock suffix")
    check(path_skip_reason("src/clock.py") is None, "clock.py is not a lock file")
    check(path_skip_reason("node_modules/pkg/index.js") is not None, "node_modules")
    check(path_skip_reason("dist/app.js") is not None, "dist")
    check(path_skip_reason("app.min.js") is not None, "minified")
    check(path_skip_reason("logo.png") is not None, "binary suffix")
    check(path_skip_reason("docs/readme.md") is None, "ordinary doc")
    check(path_skip_reason("token_size_gate.py") is not None, "gate source")
    check(path_skip_reason("CHANGELOG.md") is not None, "changelog is a log")
    check(path_skip_reason(".ai_state.md") is not None, "state journal is a log")
    check(path_skip_reason("build/app.log") is not None, ".log suffix")
    check(is_gate_infrastructure(b"# >>> token-size-gate (managed block) >>>"),
          "patched hook marker")

    check(looks_binary(b"\x89PNG\r\n\x1a\n\x00\x00") is True, "PNG is binary")
    check(looks_binary(b"hello world\n") is False, "text is not binary")
    check(looks_generated(b"// @generated by tool\n") is not None, "@generated marker")
    check(looks_generated(b"// Code generated by protoc. DO NOT EDIT.\n") is not None,
          "protoc marker")
    check(looks_generated(b"# ordinary notes\n") is None, "no false marker")
    check(looks_generated(b'{\n "generated_utc": "2026-10-19T00:00Z"\n') is not None,
          "generated_utc ledger marker")

    data = b"aaaa\nbbbb\ncccc\n"
    chunks = plan_split(data, 10)
    check(sum(chunk[2] for chunk in chunks) == len(data), "plan accounts for all bytes")
    check(all(chunk[2] <= 10 for chunk in chunks), "plan chunks fit the budget")
    check(len(chunks) == 2 and [c[2] for c in chunks] == [10, 5],
          "two lines of 5 bytes fit 10, third starts a chunk")

    one_line = b"x" * 50 + b"\n"
    flagged = plan_split(one_line, 20)
    check(flagged == [(1, 1, 51, True)], "oversized single line is flagged")

    print(f"token-size-gate selftest: OK ({checks} проверок)")
    return 0


