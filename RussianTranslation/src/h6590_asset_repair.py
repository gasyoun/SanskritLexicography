#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""H6590 (h2361 step 2): repair the displaced ASSET column of
pwg_ru/griffith_en_1896.json across the vālakhilya span (RV 8.49-8.103).

The en column was extracted from rvlinks stamps that follow the VULGATE book-8
sequence (crit 8.60-8.103 first, the vālakhilya 8.49-8.59 appended last) while
the stamps themselves are critical loci -- so every stanza in the span carries
a confidently wrong key. Macro-mapping verified by direct verse-1 readings at
all 22 hymn heads (H6590, on rvlinks + fixture DB):
  en at stamp 8.k  =  crit 8.(k+11)   for k = 49..92
  en at stamp 8.k  =  crit 8.(k-44)   for k = 93..103
with 678 = 678 stanzas both sides (bijective). The repair rekeys each stanza
in the span by rotating the flat sequence; every stanza keeps its text and
row fields, only `location` changes.

  --apply   rewrite griffith_en_1896.json in place (default: dry run)

Emits reports/H6590_griffith_asset_column_repair.md (before/after evidence).
"""
import json
import os
import sys
from collections import defaultdict

sys.stdout.reconfigure(encoding='utf-8')

HERE = os.path.dirname(os.path.abspath(__file__))
JSON_PATH = os.path.normpath(os.path.join(HERE, '..', 'pwg_ru', 'griffith_en_1896.json'))
REPORT = os.path.normpath(os.path.join(HERE, '..', 'reports',
                                       'H6590_griffith_asset_column_repair.md'))


def loc_key(loc):
    m, s, v = loc.split('.')
    return (int(m), int(s), int(v))


def loc_str(k):
    return '%d.%d.%d' % k


def main():
    apply = '--apply' in sys.argv
    with open(JSON_PATH, encoding='utf-8') as fh:
        data = json.load(fh)
    contents = data['contents']

    # the drifted span, in stamp order
    span = [r for r in contents
            if r.get('location') and loc_key(r['location'])[1] >= 49
            and loc_key(r['location'])[0] == 8]
    span.sort(key=lambda r: loc_key(r['location']))
    before = [r['location'] for r in span]

    # rotated critical reference: crit 60..103 then 49..59
    sa_keys = []
    for h in list(range(60, 104)) + list(range(49, 60)):
        # verse counts are implicit in the span's own stamp structure? No --
        # the reference must be the CRITICAL layout. Reconstruct it from the
        # en rows themselves is impossible; use the audit's fixture counts
        # via the span: the span rows' verse numbering IS the critical layout.
        pass
    # Critical layout for the span = exactly the set of stamp loci (the stamps
    # enumerate crit 8.49-8.103 1:1). The rotated reference is therefore the
    # stamp sequence reordered: crit 60..103 block first (stamps 8.60.x..
    # 8.103.x), then the valakhilya stamps 8.49.x..8.59.x.
    main_block = [r for r in span if 60 <= loc_key(r['location'])[1] <= 103]
    vala_block = [r for r in span if 49 <= loc_key(r['location'])[1] <= 59]
    reference = [loc_key(r['location']) for r in main_block + vala_block]

    assert len(span) == len(reference) == 678, (len(span), len(reference))

    # sanity: the reference is a permutation of the span's loci
    assert sorted(reference) == sorted(loc_key(l) for l in before)

    mapping = []
    for row, new_loc in zip(span, reference):
        old = loc_key(row['location'])
        mapping.append((old, new_loc))
        if apply:
            row['location'] = loc_str(new_loc)

    moved = sum(1 for o, n in mapping if o != n)
    print('span stanzas: %d   rekeyed: %d   apply=%s' % (len(mapping), moved, apply))

    # before/after hymn-level table
    by_hymn = defaultdict(lambda: [0, 0])
    for o, n in mapping:
        by_hymn[o[1]][0] += 1
        if o != n:
            by_hymn[o[1]][1] += 1
    lines = [
        '# H6590 — Griffith en-1896 asset column repair: before/after mapping',
        '',
        '_Generated by `RussianTranslation/src/h6590_asset_repair.py` (h2361 step 2).',
        'Method: the rvlinks en column follows the vulgate book-8 sequence',
        '(crit 8.60-8.103, then the vālakhilya 8.49-8.59 appended); stamps are',
        'critical loci. Repair = flat rotation of the 678-stanza span onto the',
        'rotated critical reference. Macro-mapping verified by direct verse-1',
        'readings at all 22 hymn heads (en 8.49.1 = crit 8.60.1 … en 8.103.1 =',
        'crit 8.59.1), e.g. `sāṃvaraṇa`↔"Manu Samvarani", `dasyave vṛka`↔',
        '"Dasyave-vrka", `bhāgadheyāni`↔"these shares"._',
        '',
        '| stamp hymn (before) | stanzas | rekeyed | after hymn range |',
        '|---|---|---|---|',
    ]
    after_range = {}
    for o, n in mapping:
        lo, hi = after_range.get(o[1], (n[1], n[1]))
        after_range[o[1]] = (min(lo, n[1]), max(hi, n[1]))
    for h in sorted(by_hymn):
        cnt, mv = by_hymn[h]
        lo, hi = after_range[h]
        lines.append('| 8.%d | %d | %d | 8.%d–8.%d |' % (h, cnt, mv, lo, hi))
    total_moved = sum(v[1] for v in by_hymn.values())
    lines += ['', 'Total: %d span stanzas, %d rekeyed (%.1f%%).' %
              (len(mapping), total_moved, 100.0 * total_moved / len(mapping))]

    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('report: %s' % REPORT)

    if apply:
        with open(JSON_PATH, 'w', encoding='utf-8') as fh:
            json.dump(data, fh, ensure_ascii=False, indent=1)
            fh.write('\n')
        print('APPLIED: %s rewritten' % JSON_PATH)


if __name__ == '__main__':
    main()
